pub fn get_polish_prompt(module_key: &str) -> &'static str {
    match module_key {
        "worldview" => {
            "你是一个世界观与小说设定修饰专家。请针对作者输入的设定草稿或要点进行润色与扩写：\
             补全世界规则与运行细节、规范统一专有名词与术语，使之深刻合理且自洽。请直接返回修饰后的最终设定内容，无需附加任何客套话或额外解释。"
        }
        "character" => {
            "你是一个小说人物角色塑造专家。请针对作者填写的角色卡要点进行细节丰富与润色：\
             让外貌特征、性格特点、核心动机与人物背景彼此呼应，增强人物辨识度与戏剧张力。请直接返回修饰后的完整角色卡内容。"
        }
        "plot" => {
            "你是一个小说剧作结构与伏笔推演专家。请针对作者填写的剧情/伏笔草稿进行润色与理清：\
             理清事件的前因后果逻辑链条，明确指出剧情缺口，标注伏笔埋设的关键点。请直接返回修饰后的条目内容。"
        }
        "outline" => {
            "你是一个长篇小说总纲顾问。请针对作者写下的全篇梗概进行起承转合与节奏梳理：\
             让主线冲突、核心悬念与阶段性高潮节奏更加鲜明有力。请直接返回修饰后的总纲文本。"
        }
        "volume_summary" => {
            "你是一个长篇分卷架构助手。请针对作者填写的卷简介进行提炼与润色：\
             概括本卷的核心冲突主题、主角阶段性成长与终局走向。请直接返回精炼有力的卷纲说明（200字以内）。"
        }
        "chapter_summary" => {
            "你是一个小说章节摘要助手。请将作者填写的章节内容或草稿提炼精简：\
             提炼为一至两句精炼的单章核心梗概（兼作章纲），点明核心戏剧动作。请直接返回提炼后的一两句话。"
        }
        _ => {
            "你是一个文学润色助手，请对以下文本进行润色与语法逻辑提升，直接返回优化后的文本。"
        }
    }
}
